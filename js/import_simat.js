function titleCase(str) {
  return str.toLowerCase().replace(/\p{L}+/gu, w => w[0].toUpperCase() + w.slice(1));
}

export async function importarSIMAT() {
  if (!confirm(`Esto va a registrar ${REGISTROS.length} estudiantes del listado SIMAT 2026 (grados 6° a 11°). ¿Continuar?`)) return;

  let creados = 0, omitidos = 0, errores = 0;

  for (const [documento, apellidosRaw, nombresRaw, generoLetra, grado, grupo] of REGISTROS) {

    if (state.estudiantes.some(e => e.documento === documento)) { omitidos++; continue; }

    const obj = {
      id:            genId(),
      nombres:       titleCase(nombresRaw),
      apellidos:     titleCase(apellidosRaw),
      documento,
      grado,
      grupo,
      genero:        generoLetra === 'F' ? 'Femenino' : 'Masculino',
      codigo:        genCodigo(documento),
      fechaRegistro: new Date().toISOString(),
      activo:        true
    };

    try {
      await fbSaveEstudiante(obj);
      state.estudiantes.push(obj);
      creados++;
    } catch (ex) {
      console.error('Error registrando', documento, ex);
      errores++;
    }
  }

  const resumen = `Importación SIMAT completa — Creados: ${creados}, Ya existían: ${omitidos}, Errores: ${errores}`;
  console.log(resumen);
  showToast(resumen, errores ? 'error' : 'ok');
  alert(resumen);
}
